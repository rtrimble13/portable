-- portable .port schema, version 1.
--
-- @schema_version 1
-- @name initial
--
-- Conventions, enforced by lint and by tests:
--
--   * Money, quantity, price, and rate columns are TEXT holding the canonical
--     decimal form, and carry a `-- decimal` marker. There is no REAL, FLOAT,
--     DOUBLE, or NUMERIC column anywhere in this file, and the no-float lint
--     rule fails the build if one appears. NUMERIC is on that list because
--     SQLite's NUMERIC affinity silently stores as REAL whatever it cannot
--     hold as an integer -- ADR 0005.
--   * Dates are TEXT `YYYY-MM-DD`. Timestamps are TEXT ISO-8601 UTC with a
--     trailing `Z`. Accounting uses dates; timestamps appear only where a time
--     genuinely matters (a price's as-of, a ledger row's created_at).
--   * Booleans are INTEGER CHECK (x IN (0, 1)).
--   * Every table and column comment here is the source for docs/schema.md,
--     generated by `make docs`, so it cannot drift.
--
-- Table classes (ADR 0010) -- this partition drives `pt rebuild`:
--
--   LEDGER     "transaction". Append-only, enforced by trigger.
--   REFERENCE  instrument*, price, corporate_action. Facts about the world.
--   CONFIG     account, tax_rate_schedule, benchmark*, return_policy, ...
--              Effective-dated, immutable once effective.
--   DERIVED    position*, lot*, cash_balance, valuation_snapshot*, ...
--              Dropped and rebuilt by replay.

-- No PRAGMA statements here. Connection configuration -- foreign_keys,
-- journal_mode, synchronous -- lives in persistence/connection.py, which
-- ADR 0002 makes its single home. A PRAGMA inside a migration would also
-- be a silent no-op, because migrations run inside a transaction.

-- =============================================================================
-- META
-- =============================================================================

-- @table schema_migration
-- Applied migrations, one row each. Mirrors fafnir's `meta.schema_migration`
-- so that anyone who has read that warehouse recognises this one.
CREATE TABLE IF NOT EXISTS schema_migration (
    -- Monotonic migration number. Never reused, never renumbered.
    version     INTEGER PRIMARY KEY,
    -- Short slug from the migration filename.
    name        TEXT NOT NULL,
    -- SHA-256 of the up-migration text as applied. A mismatch on open means
    -- the file changed after being applied, which is a corruption of the
    -- audit trail, not a routine edit.
    checksum    TEXT NOT NULL,
    -- ISO-8601 UTC.
    applied_at  TEXT NOT NULL,
    -- The portable version that applied it.
    applied_by  TEXT NOT NULL
);

-- @table meta
-- Portfolio-level metadata as key/value, so that adding a property is not a
-- migration. The keys `schema_version`, `portfolio_name`, `inception_date`,
-- `base_currency`, `fiscal_year_end`, `created_at`, `updated_at`, and
-- `portable_version` are required and are validated by `pt validate`.
CREATE TABLE IF NOT EXISTS meta (
    key         TEXT PRIMARY KEY,
    value       TEXT NOT NULL
);

-- @table meta_change_log
-- Redefinitions and name changes, with their dates and reasons
-- (PORT-GIPS-I17: "Redefinition of the reporting entity or composite, and name
-- changes -- date and description"). Append-only by convention and by
-- `pt validate`; the ledger's trigger discipline is reserved for transactions.
CREATE TABLE IF NOT EXISTS meta_change_log (
    change_id   INTEGER PRIMARY KEY,
    key         TEXT NOT NULL,
    old_value   TEXT,
    new_value   TEXT NOT NULL,
    -- The date the change takes effect, not the date it was entered.
    effective_from TEXT NOT NULL,
    reason      TEXT NOT NULL,
    created_at  TEXT NOT NULL
);

-- =============================================================================
-- REFERENCE
-- =============================================================================

-- @table instrument
-- The security master, local to this file, hydrated from a provider and
-- cached. A base row per instrument; options and bonds carry a detail row in
-- `instrument_option` / `instrument_bond` (ADR 0004 -- detail tables rather
-- than a JSON column, so that NOT NULL and CHECK actually bind).
CREATE TABLE IF NOT EXISTS instrument (
    instrument_id   INTEGER PRIMARY KEY,
    -- The instrument's current symbol. NOT an identifier: symbols are reused
    -- and reassigned. Resolution at a date goes through
    -- `instrument_symbol_history`.
    symbol          TEXT NOT NULL,
    instrument_type TEXT NOT NULL
        CHECK (instrument_type IN (
            'equity', 'etf', 'mutual_fund', 'adr', 'cash', 'money_market',
            'option', 'bond'
        )),
    name            TEXT,
    -- ISO 4217. USD only in v0.1, but carried on every row so that
    -- multi-currency is an extension rather than a migration (bootstrap §4.1).
    currency        TEXT NOT NULL DEFAULT 'USD',
    exchange        TEXT,
    cusip           TEXT,
    isin            TEXT,
    figi            TEXT,
    sector          TEXT,
    industry        TEXT,
    asset_class     TEXT,
    country         TEXT,
    is_active       INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    -- Where this row came from: 'manual', 'provider:<name>', 'import'.
    source          TEXT NOT NULL DEFAULT 'manual',
    -- The provider's own key for this instrument, so a hydration can be traced
    -- back to the row that produced it (PORT-GIPS-J03).
    provider_ref    TEXT,
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL,
    UNIQUE (symbol, instrument_type)
);

CREATE INDEX IF NOT EXISTS ix_instrument_symbol ON instrument (symbol);
CREATE INDEX IF NOT EXISTS ix_instrument_cusip ON instrument (cusip) WHERE cusip IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_instrument_isin ON instrument (isin) WHERE isin IS NOT NULL;

-- @table instrument_symbol_history
-- Ticker history, so a symbol resolves to the instrument it named *on the
-- trade date* rather than the one it names today. Mirrors fafnir's
-- `core.symbol_xref`. A rename or a relist silently rewrites history without
-- this.
CREATE TABLE IF NOT EXISTS instrument_symbol_history (
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    symbol          TEXT NOT NULL,
    valid_from      TEXT NOT NULL DEFAULT '1900-01-01',
    -- NULL means currently valid.
    valid_to        TEXT,
    is_primary      INTEGER NOT NULL DEFAULT 1 CHECK (is_primary IN (0, 1)),
    source          TEXT NOT NULL DEFAULT 'manual',
    PRIMARY KEY (instrument_id, symbol, valid_from)
);

CREATE INDEX IF NOT EXISTS ix_symbol_history_lookup
    ON instrument_symbol_history (symbol, valid_from);

-- @table instrument_option
-- Listed option detail. One row per option instrument.
CREATE TABLE IF NOT EXISTS instrument_option (
    instrument_id   INTEGER PRIMARY KEY REFERENCES instrument (instrument_id),
    underlier_instrument_id INTEGER NOT NULL REFERENCES instrument (instrument_id),
    -- Named `option_right` rather than `right`, which SQLite treats as a join
    -- keyword.
    option_right    TEXT NOT NULL CHECK (option_right IN ('call', 'put')),
    strike          TEXT NOT NULL,  -- decimal
    expiry          TEXT NOT NULL,
    -- Shares per contract. NOT NULL with no default, deliberately: it is 100
    -- until the day it is not (adjusted contracts after a split), and a
    -- defaulted multiplier is a 100x wrong number (ADR 0004).
    multiplier      TEXT NOT NULL,  -- decimal
    occ_symbol      TEXT,
    exercise_style  TEXT NOT NULL DEFAULT 'american'
        CHECK (exercise_style IN ('american', 'european')),
    -- Physical delivery into the underlier, or cash settlement.
    settlement      TEXT NOT NULL DEFAULT 'physical'
        CHECK (settlement IN ('physical', 'cash'))
);

CREATE INDEX IF NOT EXISTS ix_option_underlier
    ON instrument_option (underlier_instrument_id, expiry);

-- @table instrument_bond
-- Fixed income detail. One row per bond instrument.
CREATE TABLE IF NOT EXISTS instrument_bond (
    instrument_id     INTEGER PRIMARY KEY REFERENCES instrument (instrument_id),
    issuer            TEXT NOT NULL,
    -- Annual coupon rate as a decimal fraction: 4.25% is '0.0425'.
    coupon_rate       TEXT NOT NULL,  -- decimal
    -- Coupon payments per year. 0 for a zero-coupon bond.
    coupon_frequency  INTEGER NOT NULL CHECK (coupon_frequency IN (0, 1, 2, 4, 12)),
    maturity_date     TEXT NOT NULL,
    -- Day-count convention for accrued interest. Getting this wrong misstates
    -- accrued interest, which is part of market value (PORT-GIPS-A06).
    day_count         TEXT NOT NULL
        CHECK (day_count IN ('30/360', 'ACT/ACT', 'ACT/365', 'ACT/360')),
    face_value        TEXT NOT NULL,  -- decimal
    first_coupon_date TEXT,
    -- Whether prices are quoted per 100 of face ('percent_of_par') or as a
    -- money amount per bond ('price_per_bond').
    quote_basis       TEXT NOT NULL DEFAULT 'percent_of_par'
        CHECK (quote_basis IN ('percent_of_par', 'price_per_bond')),
    is_callable       INTEGER NOT NULL DEFAULT 0 CHECK (is_callable IN (0, 1)),
    next_call_date    TEXT,
    next_call_price   TEXT   -- decimal
);

-- @table price
-- The price cache. Every price records where it came from, when it was true,
-- how it was determined, and whether it is an estimate. This is not
-- convenience: PORT-GIPS-J03 requires supporting data for every reported
-- figure, including records obtained from third parties, and it is what makes
-- a return traceable to the ticks that produced it.
--
-- Prices are UNADJUSTED (PORT-GIPS-A01). Adjusted prices are not fair values
-- on the measurement date and would double-count splits.
CREATE TABLE IF NOT EXISTS price (
    price_id        INTEGER PRIMARY KEY,
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    price_date      TEXT NOT NULL,
    price           TEXT NOT NULL,  -- decimal
    currency        TEXT NOT NULL DEFAULT 'USD',
    -- 'manual', 'file:<path>', 'fafnir:core.daily_price', ...
    source          TEXT NOT NULL,
    -- When the source asserted this price. ISO-8601 UTC.
    as_of           TEXT NOT NULL,
    -- The GIPS fair-value hierarchy, PORT-GIPS-A02 / Firms 2.B.6:
    --   1 unadjusted quoted prices for identical investments, active markets
    --   2 observable quoted prices for similar investments, active markets
    --   3 quoted prices for identical or similar, non-active markets
    --   4 observable market-based inputs other than quoted prices
    --   5 subjective, unobservable inputs
    -- Provider EOD closes are 1. A price set by hand with no documented basis
    -- is 5, so that it shows up in the level-5 percentage (PORT-GIPS-H05)
    -- rather than hiding among the observable ones.
    valuation_level INTEGER NOT NULL CHECK (valuation_level BETWEEN 1 AND 5),
    -- How the number was arrived at, alongside the hierarchy level.
    valuation_basis TEXT NOT NULL
        CHECK (valuation_basis IN ('exchange_close', 'model', 'estimate', 'manual')),
    -- Preliminary or estimated values must be flagged, and when the final
    -- value arrives the affected snapshots must be rebuilt (PORT-GIPS-A09).
    is_estimate     INTEGER NOT NULL DEFAULT 0 CHECK (is_estimate IN (0, 1)),
    -- The provider's own row key, e.g. 'security_id=42;trade_date=2026-03-31;
    -- ingestion_run_id=91'. Lineage, per PORT-GIPS-J03.
    provider_ref    TEXT,
    created_at      TEXT NOT NULL,
    UNIQUE (instrument_id, price_date, source)
);

CREATE INDEX IF NOT EXISTS ix_price_instrument_date ON price (instrument_id, price_date);
CREATE INDEX IF NOT EXISTS ix_price_date ON price (price_date);

-- @table corporate_action
-- Corporate actions as reported by a provider. This is the *reference* record
-- of what the world did. Applying it to the portfolio produces one or more
-- ledger transactions -- the action itself never changes derived state
-- directly, so that `pt rebuild` reproduces its effect from the ledger.
CREATE TABLE IF NOT EXISTS corporate_action (
    corporate_action_id INTEGER PRIMARY KEY,
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    action_type     TEXT NOT NULL
        CHECK (action_type IN (
            'split', 'reverse_split', 'stock_dividend', 'cash_dividend',
            'spinoff', 'merger', 'symbol_change', 'delist', 'return_of_capital'
        )),
    -- Entitlement is determined on the ex-date; cash arrives on the pay date.
    -- Both are recorded because accruing on the wrong one shifts return across
    -- a period boundary (PORT-GIPS-A06).
    ex_date         TEXT NOT NULL,
    record_date     TEXT,
    pay_date        TEXT,
    declared_date   TEXT,
    -- 2-for-1 is numerator 2, denominator 1.
    split_numerator TEXT,   -- decimal
    split_denominator TEXT, -- decimal
    cash_amount     TEXT,   -- decimal
    -- For spinoffs and mergers: the instrument received.
    target_instrument_id INTEGER REFERENCES instrument (instrument_id),
    -- Shares of target per share held.
    target_ratio    TEXT,   -- decimal
    -- Relative fair market values used to allocate basis in a spinoff. Stored
    -- because the allocation is only defensible if the inputs are recorded.
    parent_fmv      TEXT,   -- decimal
    target_fmv      TEXT,   -- decimal
    new_symbol      TEXT,
    source          TEXT NOT NULL DEFAULT 'manual',
    provider_ref    TEXT,
    -- Whether this action has been applied to the ledger.
    applied_txn_id  INTEGER,
    created_at      TEXT NOT NULL,
    UNIQUE (instrument_id, action_type, ex_date)
);

CREATE INDEX IF NOT EXISTS ix_ca_instrument_date ON corporate_action (instrument_id, ex_date);

