-- LEDGER -- append-only, the source of truth
-- =============================================================================

-- @table transaction
-- The immutable ledger. Everything else about the portfolio is derived from
-- these rows (ADR 0010).
--
-- UPDATE and DELETE are rejected by trigger. A mistake is corrected with a
-- reversing entry plus a new entry, never by editing history -- that is what
-- makes the tax trail defensible and what makes `--as-of` time travel mean
-- something.
--
-- Replay order is (trade_date, seq, txn_id). NOT created_at: a wall clock is
-- not a total order across machines and CLAUDE.md invariant 6 forbids
-- depending on one. NOT trade_date alone: two trades on one day in the wrong
-- order consume the wrong lots under FIFO.
CREATE TABLE IF NOT EXISTS "transaction" (
    txn_id          INTEGER PRIMARY KEY,
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    -- Recognition is on trade date (PORT-GIPS-A05). Settlement is recorded but
    -- does not drive position or P&L recognition. This is stricter than the
    -- archived T+3 accommodation, whose Q&A lapsed on 2019-12-31.
    trade_date      TEXT NOT NULL,
    settlement_date TEXT,
    -- Sequence within the trade date, assigned at insert from the ledger's
    -- existing maximum. Gives the ledger a total order that does not depend on
    -- a clock.
    seq             INTEGER NOT NULL,
    txn_type        TEXT NOT NULL CHECK (txn_type IN (
        -- trades
        'buy', 'sell', 'sell_short', 'buy_to_cover',
        -- cash
        'deposit', 'withdrawal', 'transfer', 'journal',
        'interest', 'fee', 'margin_interest',
        -- income
        'dividend', 'dividend_reinvest', 'return_of_capital', 'coupon',
        'accrual_income',
        -- corporate actions
        'split', 'reverse_split', 'stock_dividend', 'spinoff',
        'merger_cash', 'merger_stock', 'merger_mixed', 'symbol_change', 'delist',
        -- options lifecycle
        'option_exercise', 'option_assignment', 'option_expiration',
        -- fixed income lifecycle
        'bond_amortization', 'bond_accretion', 'bond_call', 'bond_maturity',
        -- adjustments
        'reversal', 'correction'
    )),
    instrument_id   INTEGER REFERENCES instrument (instrument_id),
    quantity        TEXT,  -- decimal
    price           TEXT,  -- decimal
    gross_amount    TEXT,  -- decimal
    -- Always canonical 2dp, so that '0.00' is an exact test for "no fee" and
    -- the fee_class CHECK below can bind without numeric comparison in SQL.
    fees            TEXT NOT NULL DEFAULT '0.00',  -- decimal
    commissions     TEXT NOT NULL DEFAULT '0.00',  -- decimal
    taxes_withheld  TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- Reclaimable withholding is accrued; non-reclaimable reduces return
    -- (PORT-GIPS-A06 / Firms 2.B.5). Splitting them is the only way to get
    -- both right.
    withholding_reclaimable TEXT,  -- decimal
    -- The three return bases are DERIVED from this (PORT-GIPS-D01). NULL where
    -- a fee is present must be an error, not a silent default -- the CHECK
    -- below is what makes that true for every writer, including `pt import`
    -- and any future broker adapter.
    --
    -- Note that under the Asset Owner ladder `portable` follows, a custody fee
    -- is an internal_mgmt_cost and reduces net-of-fees only. It is NOT a
    -- transaction_cost, in either regime.
    fee_class       TEXT CHECK (fee_class IN (
        'transaction_cost', 'embedded_fund_fee', 'external_mgmt_fee',
        'internal_mgmt_cost', 'other_admin'
    )),
    -- Signed effect on the account's cash balance.
    net_cash_effect TEXT NOT NULL,  -- decimal
    position_id     INTEGER,
    -- For a transfer: the other side. ONE transaction, not two, so that
    -- portfolio-level netting is structural rather than a matching heuristic
    -- (ADR 0007). At portfolio level a transfer yields NO flow -- not two
    -- flows that happen to cancel, which would still break a sub-period.
    counter_account_id INTEGER REFERENCES account (account_id),
    -- Links a roll's close to its open, an assignment to its stock leg, a
    -- spinoff's parent to its child.
    related_txn_id  INTEGER REFERENCES "transaction" (txn_id),
    -- Set on a reversal, pointing at what it reverses.
    reverses_txn_id INTEGER REFERENCES "transaction" (txn_id),
    -- Explicit lot designation for spec-ID, as 'lot_id:qty;lot_id:qty'.
    lot_selection   TEXT,
    relief_method   TEXT CHECK (relief_method IN
        ('spec', 'fifo', 'lifo', 'hifo', 'lofo', 'avg')),
    -- Income dates. Entitlement on ex_date, cash on pay_date.
    ex_date         TEXT,
    pay_date        TEXT,
    -- Qualified dividend flag; NULL where not applicable.
    is_qualified    INTEGER CHECK (is_qualified IN (0, 1)),
    note            TEXT,
    -- The broker confirm id. Used for duplicate detection on import.
    external_ref    TEXT,
    source          TEXT NOT NULL DEFAULT 'manual'
        CHECK (source IN ('manual', 'import', 'derived')),
    -- Wall-clock provenance. Recorded, but NEVER used for ordering.
    created_at      TEXT NOT NULL,
    UNIQUE (trade_date, seq),
    -- PORT-GIPS-D01: a fee with no classification is refused, not guessed.
    CHECK (
        (fees = '0.00' AND commissions = '0.00')
        OR fee_class IS NOT NULL
    ),
    -- A transfer needs somewhere to transfer to; nothing else may have one.
    CHECK (
        (txn_type = 'transfer' AND counter_account_id IS NOT NULL)
        OR (txn_type <> 'transfer' AND counter_account_id IS NULL)
    ),
    CHECK ((txn_type = 'reversal') = (reverses_txn_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ix_txn_account_date ON "transaction" (account_id, trade_date);
CREATE INDEX IF NOT EXISTS ix_txn_instrument_date ON "transaction" (instrument_id, trade_date);
CREATE INDEX IF NOT EXISTS ix_txn_position ON "transaction" (position_id);
CREATE INDEX IF NOT EXISTS ix_txn_type_date ON "transaction" (txn_type, trade_date);
CREATE INDEX IF NOT EXISTS ix_txn_order ON "transaction" (trade_date, seq);
CREATE INDEX IF NOT EXISTS ix_txn_external_ref
    ON "transaction" (external_ref) WHERE external_ref IS NOT NULL;

-- CLAUDE.md invariant 2, enforced by the database rather than by convention.
-- These triggers are the reason the audit trail is defensible: no code path,
-- including a future one nobody has written yet, can edit history.
CREATE TRIGGER IF NOT EXISTS trg_transaction_no_update
BEFORE UPDATE ON "transaction"
BEGIN
    -- RAISE() takes a string literal, so this cannot be wrapped. The
    -- fuller explanation is on PT-E-LEDGER-IMMUTABLE at the CLI boundary.
    SELECT RAISE(ABORT, 'PT-E-LEDGER-IMMUTABLE: the ledger is append-only; correct with a reversing entry (pt trade reverse), never by editing history');
END;

CREATE TRIGGER IF NOT EXISTS trg_transaction_no_delete
BEFORE DELETE ON "transaction"
BEGIN
    -- RAISE() takes a string literal, so this cannot be wrapped. The
    -- fuller explanation is on PT-E-LEDGER-IMMUTABLE at the CLI boundary.
    SELECT RAISE(ABORT, 'PT-E-LEDGER-IMMUTABLE: the ledger is append-only; correct with a reversing entry (pt trade reverse), never by deleting history');
END;

