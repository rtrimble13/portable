-- @table account
-- Accounts hold positions and cash. All transactions happen at account level.
CREATE TABLE IF NOT EXISTS account (
    account_id      INTEGER PRIMARY KEY,
    name            TEXT NOT NULL UNIQUE,
    -- Tax treatment is a first-class attribute, not a tag: it changes what a
    -- realized gain means.
    account_type    TEXT NOT NULL
        CHECK (account_type IN ('taxable', 'tax_deferred', 'tax_exempt')),
    custodian       TEXT,
    -- An alias, never the real account number.
    account_alias   TEXT,
    opened_date     TEXT NOT NULL,
    closed_date     TEXT,
    status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    -- PORT-GIPS-A07 / Firms 2.A.11: returns from cash must be included in all
    -- return calculations. Asset Owners 22.B.9-.10 carve out operating cash
    -- not fully available for investment. Defaulting to 'invested' means cash
    -- drag is always in the return unless somebody explicitly says otherwise;
    -- there is no implicit ex-cash basis.
    cash_treatment  TEXT NOT NULL DEFAULT 'invested'
        CHECK (cash_treatment IN ('invested', 'operating')),
    -- Default lot relief method, overridable per closing trade.
    default_relief_method TEXT NOT NULL DEFAULT 'spec'
        CHECK (default_relief_method IN ('spec', 'fifo', 'lifo', 'hifo', 'lofo', 'avg')),
    -- Whether this account can hold fractional shares. A corporate action that
    -- would create one where it cannot is an error, not a rounding.
    allows_fractional INTEGER NOT NULL DEFAULT 0 CHECK (allows_fractional IN (0, 1)),
    sweep_instrument_id INTEGER REFERENCES instrument (instrument_id),
    currency        TEXT NOT NULL DEFAULT 'USD',
    note            TEXT,
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL,
    CHECK (closed_date IS NULL OR closed_date >= opened_date),
    CHECK (status = 'open' OR closed_date IS NOT NULL)
);

-- @table tax_rate_schedule
-- Effective-dated tax rates per account, stored as separate federal, state and
-- NIIT components so that the effective rate is explainable rather than a
-- magic number (bootstrap §4.2).
--
-- Effective-dated for the same reason `return_policy` is: a rate change must
-- not retroactively restate what last year's sale cost.
CREATE TABLE IF NOT EXISTS tax_rate_schedule (
    rate_id         INTEGER PRIMARY KEY,
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    effective_from  TEXT NOT NULL,
    -- Decimal fractions: 37% is '0.37'.
    short_term_federal TEXT NOT NULL,  -- decimal
    long_term_federal  TEXT NOT NULL,  -- decimal
    state              TEXT NOT NULL DEFAULT '0',  -- decimal
    niit               TEXT NOT NULL DEFAULT '0',  -- decimal
    -- Rate applied to qualified dividends, where it differs from long-term.
    qualified_dividend TEXT,  -- decimal
    note            TEXT,
    created_at      TEXT NOT NULL,
    UNIQUE (account_id, effective_from)
);

-- @table benchmark
-- A benchmark series. PORT-GIPS-G01: price-only benchmarks are prohibited in
-- performance reports, and `portable` refuses rather than warns.
CREATE TABLE IF NOT EXISTS benchmark (
    benchmark_id    INTEGER PRIMARY KEY,
    name            TEXT NOT NULL UNIQUE,
    description     TEXT NOT NULL,
    -- NOT NULL with NO DEFAULT, deliberately (PORT-GIPS-G01). A defaulted
    -- return_type is how a price-only series gets used by accident, and the
    -- S&P 500 price index is far easier to obtain than its total-return
    -- counterpart while understating the benchmark by roughly the dividend
    -- yield every year -- flattering the portfolio by 1.5-2% annually.
    return_type     TEXT NOT NULL CHECK (return_type IN ('total_return', 'price_only')),
    -- Disclosed when benchmark returns are calculated less frequently than
    -- monthly (PORT-GIPS-G05).
    periodicity     TEXT NOT NULL DEFAULT 'daily'
        CHECK (periodicity IN ('daily', 'weekly', 'monthly', 'quarterly', 'annual')),
    -- Whether the series is net of withholding taxes, where known
    -- (PORT-GIPS-G05). NULL means "not available", which is itself disclosed.
    is_net_of_withholding INTEGER CHECK (is_net_of_withholding IN (0, 1)),
    -- For a blend: how components are rebalanced. An explicit rule, not a
    -- config string (PORT-GIPS-G03). e.g. 'monthly', 'quarterly', 'none',
    -- 'drift_band:5'.
    rebalance_rule  TEXT,
    is_blend        INTEGER NOT NULL DEFAULT 0 CHECK (is_blend IN (0, 1)),
    source          TEXT NOT NULL DEFAULT 'manual',
    created_at      TEXT NOT NULL,
    CHECK (is_blend = 0 OR rebalance_rule IS NOT NULL)
);

-- @table benchmark_component
-- Components of a blended policy benchmark, with effective-dated weights
-- (PORT-GIPS-G03). A blend is a stored object, not a formula in a config
-- string, because its composition must be disclosed as of each annual period
-- end.
CREATE TABLE IF NOT EXISTS benchmark_component (
    component_id    INTEGER PRIMARY KEY,
    benchmark_id    INTEGER NOT NULL REFERENCES benchmark (benchmark_id),
    -- Exactly one of these is set.
    component_benchmark_id INTEGER REFERENCES benchmark (benchmark_id),
    component_instrument_id INTEGER REFERENCES instrument (instrument_id),
    weight          TEXT NOT NULL,  -- decimal
    effective_from  TEXT NOT NULL,
    label           TEXT,
    CHECK (
        (component_benchmark_id IS NOT NULL AND component_instrument_id IS NULL)
        OR (component_benchmark_id IS NULL AND component_instrument_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_benchmark_component
    ON benchmark_component (benchmark_id, effective_from);

-- @table benchmark_level
-- Observed benchmark index levels or period returns. Kept separate from
-- `price` because a benchmark is not an instrument and must not accidentally
-- be valued as one.
CREATE TABLE IF NOT EXISTS benchmark_level (
    benchmark_id    INTEGER NOT NULL REFERENCES benchmark (benchmark_id),
    level_date      TEXT NOT NULL,
    -- Index level. Total-return series only, per PORT-GIPS-G01.
    level           TEXT NOT NULL,  -- decimal
    source          TEXT NOT NULL,
    as_of           TEXT NOT NULL,
    PRIMARY KEY (benchmark_id, level_date)
);

-- @table portfolio_benchmark
-- Which benchmark applies to the portfolio, effective-dated, with the reason
-- for every change (PORT-GIPS-G04: disclose the date and description of any
-- benchmark change; prospective changes are disclosed for as long as returns
-- for the prior benchmark remain in the report).
CREATE TABLE IF NOT EXISTS portfolio_benchmark (
    id              INTEGER PRIMARY KEY,
    benchmark_id    INTEGER NOT NULL REFERENCES benchmark (benchmark_id),
    effective_from  TEXT NOT NULL,
    change_type     TEXT NOT NULL CHECK (change_type IN ('prospective', 'retroactive')),
    change_reason   TEXT NOT NULL,
    created_at      TEXT NOT NULL,
    UNIQUE (effective_from, benchmark_id)
);

-- @table return_policy
-- Effective-dated thresholds that GIPS requires an entity to define and
-- supplies no number for (PORT-GIPS-B03, E09, J01).
--
-- These are NOT configuration. They live in the .port file because they must
-- be reconstructible for historical periods: a threshold that lived in
-- ~/.portablerc could not be recovered for a period that ended two years ago.
-- Effective-dated for the same reason tax rates are.
--
-- A missing policy is an ERROR, not a zero (PT-E-GIPS-NO-FLOW-POLICY).
CREATE TABLE IF NOT EXISTS return_policy (
    policy_id       INTEGER PRIMARY KEY,
    effective_from  TEXT NOT NULL UNIQUE,
    -- LARGE cash flow: the level at which a flow may distort the return if the
    -- portfolio is not valued and a sub-period return calculated. Triggers
    -- revaluation. GIPS glossary; the amount must be defined by the asset
    -- owner in currency or as a percentage of assets.
    large_flow_basis TEXT NOT NULL CHECK (large_flow_basis IN ('amount', 'percent')),
    large_flow_value TEXT NOT NULL,  -- decimal
    -- SIGNIFICANT cash flow: a DIFFERENT threshold for a DIFFERENT purpose --
    -- temporary removal of a portfolio from a composite. A flow can be one
    -- without being the other, so these are separate fields and not one
    -- (PORT-GIPS-E09). NULL until composites exist (v1.0).
    significant_flow_basis TEXT
        CHECK (significant_flow_basis IS NULL OR significant_flow_basis IN ('amount', 'percent')),
    significant_flow_value TEXT,  -- decimal
    -- Materiality for error correction. GIPS supplies no number here either
    -- (PORT-GIPS-J01): the entity defines it. Two thresholds, whichever binds
    -- first.
    materiality_return_bps TEXT,  -- decimal
    materiality_value      TEXT,  -- decimal
    -- Which return basis feeds the risk measures. GIPS recommends
    -- gross-of-fees and requires the choice be disclosed (PORT-GIPS-F04).
    risk_measure_basis TEXT NOT NULL DEFAULT 'gross_of_fees'
        CHECK (risk_measure_basis IN
            ('gross_of_fees', 'net_of_external_costs_only', 'net_of_fees')),
    note            TEXT,
    created_at      TEXT NOT NULL,
    CHECK ((significant_flow_basis IS NULL) = (significant_flow_value IS NULL))
);

-- @table portfolio_event
-- Significant events that help a reader interpret a report (PORT-GIPS-I08 /
-- AO 24.C.16). Disclosed for a minimum of one year and as long as relevant --
-- `expiry_date` carries that, so the disclosure engine can drop it on
-- schedule rather than relying on somebody remembering.
CREATE TABLE IF NOT EXISTS portfolio_event (
    event_id        INTEGER PRIMARY KEY,
    event_date      TEXT NOT NULL,
    description     TEXT NOT NULL,
    -- NULL means "no expiry set"; the engine then applies the one-year floor.
    expiry_date     TEXT,
    created_at      TEXT NOT NULL
);

-- @table report_issue
-- Issued reports, for error detection and correction (PORT-GIPS-J01, J02).
--
-- The content hash is what makes this cheap and exact, and `portable`'s
-- determinism guarantee is what makes the hash meaningful (PORT-GIPS-J06):
-- rebuild a report, hash it, compare. A correction is a NEW issue referencing
-- the superseded one -- the same discipline the ledger imposes on
-- transactions, extended to reports.
CREATE TABLE IF NOT EXISTS report_issue (
    report_issue_id INTEGER PRIMARY KEY,
    -- Stable identity of the report, e.g. 'annual:2025' or 'tax:2025'.
    report_id       TEXT NOT NULL,
    issued_at       TEXT NOT NULL,
    -- SHA-256 of the canonical JSON output.
    content_hash    TEXT NOT NULL,
    command         TEXT NOT NULL,
    params_json     TEXT NOT NULL,
    -- Set on the OLD row when a corrected issue replaces it. Never deleted.
    superseded_by   INTEGER REFERENCES report_issue (report_issue_id),
    -- Why it was superseded, and whether the difference was material.
    correction_reason TEXT,
    is_material     INTEGER CHECK (is_material IN (0, 1)),
    created_at      TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_report_issue_report ON report_issue (report_id, issued_at);

-- @table settings
-- Portfolio-scoped settings. Distinct from `meta` (identity) and from
-- `return_policy` (effective-dated methodology), and distinct again from
-- ~/.portablerc, which is user-scoped and not part of the portfolio.
CREATE TABLE IF NOT EXISTS settings (
    key             TEXT PRIMARY KEY,
    value           TEXT NOT NULL,
    updated_at      TEXT NOT NULL
);

