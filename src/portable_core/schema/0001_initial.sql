-- @table position
-- The container, and the unit of trader intent. A position MAY SPAN MULTIPLE
-- INSTRUMENTS: a covered call is one position, not two (ADR 0009).
CREATE TABLE IF NOT EXISTS position (
    position_id     INTEGER PRIMARY KEY,
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    strategy_type   TEXT NOT NULL DEFAULT 'single'
        CHECK (strategy_type IN (
            'single', 'covered_call', 'vertical', 'calendar', 'diagonal',
            'collar', 'straddle', 'strangle', 'custom'
        )),
    opened_date     TEXT NOT NULL,
    closed_date     TEXT,
    status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    label           TEXT,
    note            TEXT,
    -- The transaction that opened it, so replay can reproduce identity.
    opened_txn_id   INTEGER REFERENCES "transaction" (txn_id),
    CHECK (status = 'open' OR closed_date IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_position_account_status ON position (account_id, status);

-- @table position_leg
-- Binds one instrument to a position with a role and a sign. The role is what
-- lets the engines know that *this* short call is written against *that*
-- stock, which is what makes assignment a within-position operation rather
-- than a cross-position fixup (ADR 0009).
CREATE TABLE IF NOT EXISTS position_leg (
    leg_id          INTEGER PRIMARY KEY,
    position_id     INTEGER NOT NULL REFERENCES position (position_id),
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    role            TEXT NOT NULL CHECK (role IN (
        'underlying', 'long_call', 'short_call', 'long_put', 'short_put',
        'long_stock', 'short_stock', 'bond', 'hedge', 'other'
    )),
    -- +1 long, -1 short.
    sign            INTEGER NOT NULL CHECK (sign IN (-1, 1)),
    -- Materialized from the leg's open lots. The per-leg form of CLAUDE.md
    -- invariant 5: sum(lot.remaining_quantity) == leg.quantity. Per LEG, not
    -- per position -- a position spanning two instruments has no scalar
    -- quantity, so stating the invariant per position would be meaningless
    -- for exactly the case the model exists for (ADR 0009).
    quantity        TEXT NOT NULL DEFAULT '0',  -- decimal
    opened_date     TEXT NOT NULL,
    closed_date     TEXT,
    status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    UNIQUE (position_id, instrument_id, role)
);

CREATE INDEX IF NOT EXISTS ix_leg_position ON position_leg (position_id);
CREATE INDEX IF NOT EXISTS ix_leg_instrument ON position_leg (instrument_id, status);

-- @table lot
-- Created by an opening transaction, consumed by closing ones. Lots are the
-- tax engine's atoms. A lot hangs off a LEG, not off a position, because a lot
-- must resolve to exactly one instrument and a position need not.
CREATE TABLE IF NOT EXISTS lot (
    lot_id          INTEGER PRIMARY KEY,
    leg_id          INTEGER NOT NULL REFERENCES position_leg (leg_id),
    position_id     INTEGER NOT NULL REFERENCES position (position_id),
    -- Denormalised for the queries the LotEngine actually runs.
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    open_date       TEXT NOT NULL,
    open_txn_id     INTEGER NOT NULL REFERENCES "transaction" (txn_id),
    original_quantity  TEXT NOT NULL,  -- decimal
    remaining_quantity TEXT NOT NULL,  -- decimal
    per_unit_price     TEXT NOT NULL,  -- decimal
    allocated_fees     TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- Basis as originally established, before adjustments. Kept so that the
    -- adjustment log can be checked against it.
    original_cost_basis TEXT NOT NULL,  -- decimal
    -- Basis as it now stands. Every change is explained by a row in
    -- lot_basis_adjustment.
    adjusted_cost_basis TEXT NOT NULL,  -- decimal
    -- Long-term requires MORE THAN ONE YEAR measured from the DAY AFTER
    -- acquisition. A split does not reset this; a spinoff's new shares inherit
    -- it. Wash sales (v0.2) will move it.
    holding_period_start TEXT NOT NULL,
    -- Short sales are always short-term regardless of holding period.
    is_short        INTEGER NOT NULL DEFAULT 0 CHECK (is_short IN (0, 1)),
    status          TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'partial', 'closed')),
    closed_date     TEXT,
    CHECK (status <> 'closed' OR closed_date IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_lot_leg ON lot (leg_id, status);
CREATE INDEX IF NOT EXISTS ix_lot_instrument_account
    ON lot (instrument_id, account_id, status);
CREATE INDEX IF NOT EXISTS ix_lot_open_date ON lot (open_date);

-- @table lot_basis_adjustment
-- Every change to a lot's basis or holding-period start, with its reason. This
-- log is the difference between a basis you can defend and one you can only
-- assert.
CREATE TABLE IF NOT EXISTS lot_basis_adjustment (
    adjustment_id   INTEGER PRIMARY KEY,
    lot_id          INTEGER NOT NULL REFERENCES lot (lot_id),
    adjustment_date TEXT NOT NULL,
    reason          TEXT NOT NULL CHECK (reason IN (
        'commission', 'fee', 'return_of_capital', 'split', 'reverse_split',
        'stock_dividend', 'spinoff', 'merger', 'option_premium_exercise',
        'option_premium_assignment', 'amortization', 'accretion',
        'wash_sale', 'manual_correction', 'forced_zero_basis'
    )),
    -- Signed change to adjusted_cost_basis.
    basis_delta     TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- Signed change to quantity (a split multiplies; this records the delta).
    quantity_delta  TEXT NOT NULL DEFAULT '0',  -- decimal
    -- The holding-period start after this adjustment. A split leaves it
    -- unchanged; recording it explicitly makes that assertion checkable rather
    -- than implicit.
    holding_period_start_after TEXT NOT NULL,
    txn_id          INTEGER REFERENCES "transaction" (txn_id),
    note            TEXT
);

CREATE INDEX IF NOT EXISTS ix_basis_adjustment_lot ON lot_basis_adjustment (lot_id);

-- @table lot_disposition
-- One row per (closing transaction, lot consumed). The tax engine's input.
CREATE TABLE IF NOT EXISTS lot_disposition (
    disposition_id  INTEGER PRIMARY KEY,
    lot_id          INTEGER NOT NULL REFERENCES lot (lot_id),
    txn_id          INTEGER NOT NULL REFERENCES "transaction" (txn_id),
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    disposition_date TEXT NOT NULL,
    quantity        TEXT NOT NULL,  -- decimal
    -- Includes option premium where an assignment resolved into stock: a
    -- written call that is assigned adds its premium to PROCEEDS, not to
    -- independent P&L.
    proceeds        TEXT NOT NULL,  -- decimal
    allocated_fees  TEXT NOT NULL DEFAULT '0.00',  -- decimal
    cost_basis_relieved TEXT NOT NULL,  -- decimal
    realized_gain   TEXT NOT NULL,  -- decimal
    -- Determined at disposition from the lot's holding_period_start. Short
    -- sales are always 'short'.
    holding_period  TEXT NOT NULL CHECK (holding_period IN ('short', 'long')),
    -- Days held, recorded so the boundary determination is auditable rather
    -- than having to be recomputed to be checked.
    days_held       INTEGER NOT NULL,
    relief_method   TEXT NOT NULL
        CHECK (relief_method IN ('spec', 'fifo', 'lifo', 'hifo', 'lofo', 'avg')),
    -- v0.2. Until wash-sale detection lands this is always NULL and the tax
    -- report says on its face that it does not account for wash sales.
    wash_sale_deferred TEXT  -- decimal
);

CREATE INDEX IF NOT EXISTS ix_disposition_txn ON lot_disposition (txn_id);
CREATE INDEX IF NOT EXISTS ix_disposition_account_date
    ON lot_disposition (account_id, disposition_date);
CREATE INDEX IF NOT EXISTS ix_disposition_lot ON lot_disposition (lot_id);

-- @table realized_gain
-- Per-disposition realized gain with the estimated tax applied, materialized
-- for `pt tax` and `pt pnl --net-of-tax`.
--
-- The tax figure is an ESTIMATE: gain times the account's effective-dated rate
-- for the holding period at disposition. It does not model brackets, the
-- capital-loss limitation, carryforwards, rate stacking, AMT, or any other
-- income (ADR 0011). The components are stored separately so the effective
-- rate is explainable rather than a magic number.
CREATE TABLE IF NOT EXISTS realized_gain (
    realized_gain_id INTEGER PRIMARY KEY,
    disposition_id  INTEGER NOT NULL UNIQUE REFERENCES lot_disposition (disposition_id),
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    tax_year        INTEGER NOT NULL,
    disposition_date TEXT NOT NULL,
    holding_period  TEXT NOT NULL CHECK (holding_period IN ('short', 'long')),
    proceeds        TEXT NOT NULL,  -- decimal
    cost_basis      TEXT NOT NULL,  -- decimal
    gain            TEXT NOT NULL,  -- decimal
    -- The rate schedule row used, so the estimate can be traced.
    rate_id         INTEGER REFERENCES tax_rate_schedule (rate_id),
    federal_rate    TEXT,  -- decimal
    state_rate      TEXT,  -- decimal
    niit_rate       TEXT,  -- decimal
    estimated_tax   TEXT,  -- decimal
    -- 0 for tax_deferred and tax_exempt accounts, where the estimate is not
    -- merely zero but inapplicable; the flag says which.
    is_taxable      INTEGER NOT NULL CHECK (is_taxable IN (0, 1))
);

CREATE INDEX IF NOT EXISTS ix_realized_gain_year
    ON realized_gain (tax_year, account_id);

-- @table cash_balance
-- Current cash and margin per account and currency. Derived: the authoritative
-- history is the ledger, and a balance at any past date is obtained by replay
-- or from a valuation snapshot.
CREATE TABLE IF NOT EXISTS cash_balance (
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    currency        TEXT NOT NULL DEFAULT 'USD',
    balance         TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- A modelled liability, not a memo (PORT-GIPS-D04). Market value is assets
    -- MINUS this; returns are net of discretionary leverage and are not
    -- grossed up as if it did not exist.
    margin_loan     TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- The ledger position this balance reflects, for replay verification.
    last_txn_id     INTEGER REFERENCES "transaction" (txn_id),
    PRIMARY KEY (account_id, currency)
);

-- @table valuation_snapshot
-- Per account per date: the substrate `pert` needs (bootstrap §4.7).
--
-- `portable` values DAILY where prices exist. That satisfies the GIPS monthly
-- floor and the month-end requirement (PORT-GIPS-A03), satisfies the
-- recommendation to value on every external cash flow date, and removes the
-- need for any within-period approximation (PORT-GIPS-B06).
CREATE TABLE IF NOT EXISTS valuation_snapshot (
    snapshot_id     INTEGER PRIMARY KEY,
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    snapshot_date   TEXT NOT NULL,
    beginning_market_value TEXT NOT NULL,  -- decimal
    ending_market_value    TEXT NOT NULL,  -- decimal
    -- Ending market value is securities + cash - margin_loan + accrued income.
    securities_value TEXT NOT NULL,  -- decimal
    cash_balance    TEXT NOT NULL,  -- decimal
    margin_loan     TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- Accrued income is part of beginning and ending value, not a memo
    -- (PORT-GIPS-A06). Accrual is REQUIRED for interest-bearing instruments
    -- and RECOMMENDED for dividends; `portable` does both but must not
    -- describe the dividend half as required.
    accrued_interest TEXT NOT NULL DEFAULT '0.00',  -- decimal
    accrued_dividends TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- Sum of the two, materialized for the return path.
    accrued_income  TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- External cash flow at ACCOUNT level, on this date. Income is never here.
    external_flow_account TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- External cash flow at PORTFOLIO level. An inter-account transfer nets to
    -- zero here and yields NO flow at all -- see ADR 0007 and PORT-GIPS-B02.
    external_flow_portfolio TEXT NOT NULL DEFAULT '0.00',  -- decimal
    income_amount   TEXT NOT NULL DEFAULT '0.00',  -- decimal
    fees_amount     TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- Market value priced at hierarchy level 5 (subjective, unobservable
    -- inputs), for PORT-GIPS-H05. Zero for a listed portfolio -- rendered
    -- anyway, because "0%" is information and a missing row is not.
    level5_market_value TEXT NOT NULL DEFAULT '0.00',  -- decimal
    -- 0 when any position could not be priced. A snapshot that is not complete
    -- must not be silently used for a return.
    is_complete     INTEGER NOT NULL DEFAULT 1 CHECK (is_complete IN (0, 1)),
    -- 1 when any consumed price was flagged an estimate (PORT-GIPS-A09/I10).
    uses_estimates  INTEGER NOT NULL DEFAULT 0 CHECK (uses_estimates IN (0, 1)),
    UNIQUE (account_id, snapshot_date)
);

CREATE INDEX IF NOT EXISTS ix_snapshot_date ON valuation_snapshot (snapshot_date);

-- @table valuation_snapshot_price
-- The exact set of prices a snapshot consumed. This is what PORT-GIPS-J03
-- requires -- supporting data for every reported figure -- and what makes
-- PORT-GIPS-A09 workable: when a better price arrives, the snapshots that used
-- the estimate are identifiable and can be rebuilt.
CREATE TABLE IF NOT EXISTS valuation_snapshot_price (
    snapshot_id     INTEGER NOT NULL REFERENCES valuation_snapshot (snapshot_id),
    instrument_id   INTEGER NOT NULL REFERENCES instrument (instrument_id),
    price_id        INTEGER REFERENCES price (price_id),
    price           TEXT NOT NULL,  -- decimal
    quantity        TEXT NOT NULL,  -- decimal
    market_value    TEXT NOT NULL,  -- decimal
    source          TEXT NOT NULL,
    as_of           TEXT NOT NULL,
    valuation_level INTEGER NOT NULL CHECK (valuation_level BETWEEN 1 AND 5),
    is_estimate     INTEGER NOT NULL DEFAULT 0 CHECK (is_estimate IN (0, 1)),
    -- Days between price_date and snapshot_date. Zero on a normal day; a
    -- positive number is a stale price, permitted only within tolerance and
    -- only when flagged (PORT-GIPS-A09).
    staleness_days  INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (snapshot_id, instrument_id)
);

-- @table snapshot_flow
-- Individual external cash flows with DAY resolution, which is what the
-- money-weighted return requires (PORT-GIPS-C02 / Firms 2.A.29: daily external
-- cash flows for periods beginning on or after 1 January 2020).
--
-- The `level` column is the whole point: the same transaction can be an
-- external flow at account level and not one at portfolio level. The
-- classification comes from ONE service function and is never re-derived at a
-- call site (ADR 0007).
CREATE TABLE IF NOT EXISTS snapshot_flow (
    flow_id         INTEGER PRIMARY KEY,
    snapshot_id     INTEGER NOT NULL REFERENCES valuation_snapshot (snapshot_id),
    txn_id          INTEGER NOT NULL REFERENCES "transaction" (txn_id),
    account_id      INTEGER NOT NULL REFERENCES account (account_id),
    flow_date       TEXT NOT NULL,
    level           TEXT NOT NULL CHECK (level IN ('account', 'portfolio')),
    classification  TEXT NOT NULL
        CHECK (classification IN ('external', 'internal', 'income', 'cost')),
    -- Signed: positive into the portfolio, negative out.
    amount          TEXT NOT NULL,  -- decimal
    -- 1 when this flow exceeded the large-flow threshold in force on its date,
    -- which under PORT-GIPS-B03 would require revaluation and a sub-period
    -- return were daily returns not being computed.
    is_large        INTEGER NOT NULL DEFAULT 0 CHECK (is_large IN (0, 1)),
    -- In-kind transfers and stock distributions are flows valued at the time
    -- of distribution (PORT-GIPS-C02 / Firms 2.A.29.c).
    is_in_kind      INTEGER NOT NULL DEFAULT 0 CHECK (is_in_kind IN (0, 1))
);

CREATE INDEX IF NOT EXISTS ix_flow_date_level ON snapshot_flow (flow_date, level);
CREATE INDEX IF NOT EXISTS ix_flow_snapshot ON snapshot_flow (snapshot_id);
